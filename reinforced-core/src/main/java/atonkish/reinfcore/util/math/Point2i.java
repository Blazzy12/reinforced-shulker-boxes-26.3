package atonkish.reinfcore.util.math;

public class Point2i {
  // CHECKSTYLE.SUPPRESS: MemberName
  private int x;
  // CHECKSTYLE.SUPPRESS: MemberName
  private int y;

  public Point2i(int x, int y) {
    this.x = x;
    this.y = y;
  }

  public int getX() {
    return this.x;
  }

  public int getY() {
    return this.y;
  }
}
